import AppKit
import CryptoKit
import ImageIO

// MARK: - Model

/// One representation (type + bytes) of a pasteboard item, e.g. plain text, RTF, PNG.
struct ClipRep: Codable {
    let type: String
    let data: Data
}

enum ClipKind: String, Codable {
    case text, link, image, files, other
}

struct ClipItem: Codable, Identifiable {
    let id: UUID
    /// Every pasteboard item with all its representations, so pasting restores rich text, images, files, etc.
    var pasteboardItems: [[ClipRep]]
    var kind: ClipKind
    var title: String
    var detail: String
    var searchText: String
    var fingerprint: String
    var date: Date
    var pinned: Bool

    var imageRep: ClipRep? {
        pasteboardItems.first?.first { ClipCapture.imageTypes.contains($0.type) }
    }

    var filePaths: [String] {
        pasteboardItems.compactMap { reps in
            reps.first { $0.type == ClipCapture.fileURLType }
                .flatMap { URL(string: String(decoding: $0.data, as: UTF8.self)) }
                .flatMap { $0.isFileURL ? $0.path : nil }
        }
    }
}

// MARK: - Reading the pasteboard

enum ClipCapture {
    static let plainTextType = "public.utf8-plain-text"
    static let fileURLType = "public.file-url"
    static let imageTypes = ["public.png", "public.tiff", "public.jpeg", "public.heic", "com.compuserve.gif"]
    static let richTypes: Set<String> = ["public.rtf", "public.html", "com.apple.flat-rtfd"]

    /// Markers that password managers and other apps use to say "don't record this".
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ]

    /// Items bigger than this keep only their lightweight representations.
    static let maxBytes = 25 * 1024 * 1024
    static let keepWhenLarge: Set<String> = [
        "public.utf8-plain-text", "public.utf16-external-plain-text", "public.file-url",
        "public.url", "public.url-name", "public.png", "public.jpeg",
    ]

    static func capture(from pasteboard: NSPasteboard) -> ClipItem? {
        guard let pbItems = pasteboard.pasteboardItems, !pbItems.isEmpty else { return nil }
        let allTypes = Set(pbItems.flatMap { $0.types.map(\.rawValue) })
        guard allTypes.isDisjoint(with: ignoredTypes) else { return nil }

        var stored: [[ClipRep]] = pbItems.map { item in
            item.types.compactMap { type in
                item.data(forType: type).map { ClipRep(type: type.rawValue, data: $0) }
            }
        }.filter { !$0.isEmpty }

        if byteCount(stored) > maxBytes {
            stored = stored.map { $0.filter { keepWhenLarge.contains($0.type) } }.filter { !$0.isEmpty }
            if byteCount(stored) > maxBytes {
                stored = stored.map { $0.filter { !imageTypes.contains($0.type) } }.filter { !$0.isEmpty }
            }
        }
        guard !stored.isEmpty else { return nil }
        return describe(stored)
    }

    private static func byteCount(_ items: [[ClipRep]]) -> Int {
        items.reduce(0) { total, reps in total + reps.reduce(0) { $0 + $1.data.count } }
    }

    private static func describe(_ stored: [[ClipRep]]) -> ClipItem {
        let first = stored[0]
        let types = Set(first.map(\.type))
        func data(_ type: String) -> Data? { first.first { $0.type == type }?.data }

        let fileURLs: [URL] = stored.compactMap { reps in
            reps.first { $0.type == fileURLType }
                .flatMap { URL(string: String(decoding: $0.data, as: UTF8.self)) }
        }.filter(\.isFileURL)

        let text = data(plainTextType).map { String(decoding: $0, as: UTF8.self) }

        var kind = ClipKind.other
        var title = ""
        var detail = ""
        var search = ""
        var key = Data()

        if !fileURLs.isEmpty {
            kind = .files
            title = fileURLs.map(\.lastPathComponent).joined(separator: ", ")
            detail = fileURLs.count == 1
                ? (fileURLs[0].deletingLastPathComponent().path as NSString).abbreviatingWithTildeInPath
                : "\(fileURLs.count) files"
            search = fileURLs.map(\.path).joined(separator: "\n")
            key = Data(search.utf8)
        } else if let text, !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            kind = isLink(trimmed) ? .link : .text
            title = oneLine(text)
            if kind == .link {
                detail = URL(string: trimmed)?.host ?? "Link"
            } else {
                let lines = trimmed.split(omittingEmptySubsequences: false, whereSeparator: \.isNewline).count
                let chars = text.count
                detail = lines > 1 ? "\(lines) lines" : "\(chars) character\(chars == 1 ? "" : "s")"
                if !types.isDisjoint(with: richTypes) { detail += " · formatted" }
            }
            search = String(text.prefix(20_000))
            key = Data(text.utf8)
        } else if let imageType = imageTypes.first(where: types.contains), let imageData = data(imageType) {
            kind = .image
            title = "Image"
            if let (w, h) = pixelSize(imageData) {
                detail = "\(w) × \(h)"
            } else {
                detail = imageType.replacingOccurrences(of: "public.", with: "").uppercased()
            }
            search = "image picture screenshot"
            key = imageData
        } else {
            title = first[0].type
            detail = "Other content"
            search = title
            key = first[0].data
        }

        let digest = SHA256.hash(data: key).map { String(format: "%02x", $0) }.joined()
        return ClipItem(id: UUID(), pasteboardItems: stored, kind: kind, title: title, detail: detail,
                        searchText: search, fingerprint: "\(kind.rawValue):\(digest)", date: Date(), pinned: false)
    }

    private static func oneLine(_ text: String) -> String {
        let collapsed = text.prefix(2000).split(whereSeparator: { $0.isWhitespace || $0.isNewline }).joined(separator: " ")
        return String(collapsed.prefix(300))
    }

    private static func isLink(_ text: String) -> Bool {
        guard !text.contains(where: { $0.isWhitespace }),
              let url = URL(string: text), let scheme = url.scheme?.lowercased() else { return false }
        return ["http", "https", "ftp"].contains(scheme) && url.host != nil
    }

    static func pixelSize(_ data: Data) -> (Int, Int)? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              let props = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let w = props[kCGImagePropertyPixelWidth] as? Int,
              let h = props[kCGImagePropertyPixelHeight] as? Int else { return nil }
        return (w, h)
    }
}

// MARK: - History store (in memory + saved to disk)

final class ClipboardStore {
    private(set) var items: [ClipItem] = []
    var onChange: (() -> Void)?

    /// Like Windows: pinned items are kept forever, the rest is capped.
    let maxUnpinned = 50

    private let fileURL: URL
    private let saveQueue = DispatchQueue(label: "clipboard-history.save", qos: .utility)
    private var saveScheduled = false

    init() {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        let dir = base.appendingPathComponent("Clipboard History", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true,
                                                 attributes: [.posixPermissions: 0o700])
        fileURL = dir.appendingPathComponent("history.plist")
    }

    func load() {
        guard let data = try? Data(contentsOf: fileURL),
              let decoded = try? PropertyListDecoder().decode([ClipItem].self, from: data) else { return }
        items = decoded
    }

    func item(_ id: UUID) -> ClipItem? { items.first { $0.id == id } }

    func contains(fingerprint: String) -> Bool { items.contains { $0.fingerprint == fingerprint } }

    func add(_ newItem: ClipItem) {
        var item = newItem
        if let existing = items.firstIndex(where: { $0.fingerprint == item.fingerprint }) {
            item.pinned = items[existing].pinned
            items.remove(at: existing)
        }
        items.insert(item, at: 0)
        trim()
        changed()
    }

    /// Selected from the list: it becomes the newest item again.
    func markUsed(id: UUID) {
        guard let index = items.firstIndex(where: { $0.id == id }) else { return }
        var item = items.remove(at: index)
        item.date = Date()
        items.insert(item, at: 0)
        changed()
    }

    func togglePin(id: UUID) {
        guard let index = items.firstIndex(where: { $0.id == id }) else { return }
        items[index].pinned.toggle()
        trim()
        changed()
    }

    func remove(id: UUID) {
        items.removeAll { $0.id == id }
        changed()
    }

    func clearUnpinned() {
        items.removeAll { !$0.pinned }
        changed()
    }

    func write(_ item: ClipItem, to pasteboard: NSPasteboard) {
        let objects: [NSPasteboardItem] = item.pasteboardItems.map { reps in
            let pbItem = NSPasteboardItem()
            for rep in reps {
                pbItem.setData(rep.data, forType: NSPasteboard.PasteboardType(rep.type))
            }
            return pbItem
        }
        pasteboard.clearContents()
        pasteboard.writeObjects(objects)
    }

    func saveNow() {
        let snapshot = items
        let url = fileURL
        saveQueue.sync { Self.persist(snapshot, to: url) }
    }

    private func trim() {
        var unpinned = 0
        items = items.filter { item in
            if item.pinned { return true }
            unpinned += 1
            return unpinned <= maxUnpinned
        }
    }

    private func changed() {
        onChange?()
        scheduleSave()
    }

    private func scheduleSave() {
        guard !saveScheduled else { return }
        saveScheduled = true
        DispatchQueue.main.asyncAfter(deadline: .now() + 1) { [weak self] in
            guard let self else { return }
            self.saveScheduled = false
            let snapshot = self.items
            let url = self.fileURL
            self.saveQueue.async { Self.persist(snapshot, to: url) }
        }
    }

    private static func persist(_ items: [ClipItem], to url: URL) {
        let encoder = PropertyListEncoder()
        encoder.outputFormat = .binary
        guard let data = try? encoder.encode(items) else { return }
        try? data.write(to: url, options: [.atomic])
        try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
    }
}

// MARK: - Watching for ⌘C (or any other copy)

/// macOS has no "clipboard changed" notification, so poll the change counter (very cheap).
final class PasteboardMonitor {
    var onChange: (() -> Void)?
    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?

    init() { lastChangeCount = pasteboard.changeCount }

    func start() {
        let timer = Timer(timeInterval: 0.3, repeats: true) { [weak self] _ in self?.check() }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    /// Call after we write to the pasteboard ourselves so it isn't recorded twice.
    func skipCurrentChange() { lastChangeCount = pasteboard.changeCount }

    private func check() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        onChange?()
    }
}
